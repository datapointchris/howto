"""What the shell needs from howto, emitted by howto.

A shell rc carries one line per block, and howto carries the block. Each block
names howto's own verbs and paths, so a block kept in a config repo would carry
those details away from the code that owns them and break whenever one moved.

Two blocks, because they load at different points. The completion is an
autoloadable function that goes on `fpath` before `compinit`. The widgets are
plain definitions, sourced anywhere, and bound to a key by the rc that knows the
keymap.

The completion spawns nothing on Tab. Card and Lab ids are globbed out of the
library directory, which is what zsh's own file completion would do, so a Tab
costs a directory read rather than a Python start.
"""

from typing import Annotated

import typer

from howto.paths import library_dir

SHELL_HELP = """The blocks your shell loads from howto.

Examples:

```text
eval "$(howto shell widgets zsh)"     in .zshrc: put a pick on the prompt
eval "$(howto shell completion zsh)"  in .zshrc: complete verbs and ids
```
"""

app = typer.Typer(name='shell', no_args_is_help=True, help=SHELL_HELP)

SHELLS = ('zsh',)


def zsh_completion() -> str:
    """Completion for the verbs, and for card and Lab ids out of the library.

    The first line is `#compdef`, so it autoloads from `fpath`. The `funcstack`
    check at the end runs the completion when autoloaded and only registers it
    when sourced, the guard cobra and clap emit too.
    """
    library = library_dir()
    return f"""\
#compdef howto
# Generated by `howto shell completion zsh`; edit it there, not here.

_howto_ids() {{
  local dir="${{HOWTO_LIBRARY_DIR:-{library}}}/$1"
  local -a ids
  ids=("$dir"/*.md(N:t:r))
  _describe -t "$1" "$2" ids
}}

_howto() {{
  local -a verbs
  verbs=(
    'find:Search everything, and open what you pick'
    'show:How to use one tool or command'
    'choose:Pick one thing and print what you would type to run it'
    'list:Every indexed row, as the picker sees it'
    'cards:The reference cards'
    'tools:The tool registry'
    'labs:Hands-on practice Labs'
    'library:The library checkout: cards, Labs and the tool registry'
    'shell:The blocks your shell loads from howto'
  )

  if (( CURRENT == 2 )); then
    _describe -t verbs 'howto command' verbs
    return
  fi

  if (( CURRENT == 3 )); then
    local -a sub
    case "$words[2]" in
      cards) sub=('list:Every card' 'show:Render one card' 'new:Create a card' 'random:Render a card at random') ;;
      tools) sub=('list:Every tool, by category' 'show:One tool' 'categories:The categories') ;;
      labs) sub=('list:Every Lab' 'show:Open a Lab' 'choose:Pick a Lab' 'flash:Recall drill' 'new:Create a Lab' 'edit:Edit a Lab') ;;
      library) sub=('sync:Pull the library' 'status:Its path and uncommitted work' 'path:Print its path' 'edit:Open a card or Lab') ;;
      shell) sub=('widgets:The line-editor block' 'completion:This completion') ;;
    esac
    (( $#sub )) && _describe -t subcommands 'howto subcommand' sub
    return
  fi

  if (( CURRENT == 4 )); then
    case "$words[2] $words[3]" in
      'cards show') _howto_ids cards card ;;
      'labs show'|'labs edit') _howto_ids labs Lab ;;
      'library edit') _howto_ids cards card; _howto_ids labs Lab ;;
      'shell widgets'|'shell completion') _values shell zsh ;;
    esac
  fi
}}

if [[ "$funcstack[1]" == _howto ]]; then
  _howto "$@"
else
  compdef _howto howto
fi
"""


def zsh_widgets() -> str:
    """The line-editor half of `howto choose`.

    howto is a subprocess and the line editor belongs to its parent, so the
    insert is something howto can only ever emit. What it emits names one public
    verb and nothing else, which keeps it from breaking when howto's internals
    move.

    No `bindkey` is emitted with it. howto cannot see what the keymap already
    holds, so a chord chosen here is one taken from whatever had it — the block
    defines the widget and names it, and the rc that knows the keymap binds it.
    """
    return """\
# howto — pick anything indexed and land it on the command line, ready to run or
# edit. Generated by `howto shell widgets zsh`; edit it there, not here.
# Bind the widget where you know the keymap: bindkey '^X^D' howto-choose-widget

# Replaces the line you are on.
howto-choose-widget() {
  local chosen
  chosen="$(howto choose)"
  if [[ -n "$chosen" ]]; then
    BUFFER="$chosen"
    CURSOR=${#BUFFER}
  fi
  # fzf paints over the prompt and does not put it back.
  zle reset-prompt
}
zle -N howto-choose-widget

# Loads the next prompt instead, for when the line you are on is worth keeping.
howto-choose-next() {
  local chosen
  chosen="$(howto choose "$@")"
  [[ -n "$chosen" ]] && print -z -- "$chosen"
}
"""


GENERATORS = {
    'zsh': {'completion': zsh_completion, 'widgets': zsh_widgets},
}


def emit(shell: str, kind: str) -> int:
    if shell not in GENERATORS:
        raise typer.BadParameter(f'no {kind} for {shell}; howto generates: {", ".join(SHELLS)}')
    # Plain print: this is a script another process evals, not a message.
    print(GENERATORS[shell][kind]())
    return 0


ShellArgument = Annotated[str, typer.Argument(help=f'Which shell: {", ".join(SHELLS)}.')]


@app.command('widgets')
def shell_widgets_command(shell: ShellArgument) -> None:
    """Print the line-editor block that lands a `howto choose` pick on the prompt.

    Add `eval "$(howto shell widgets zsh)"` to your rc, then bind the widget it
    defines: `bindkey '^X^D' howto-choose-widget`. The chord is yours to pick,
    because howto cannot see what your keymap already holds.

    zsh only, because `print -z` and the ZLE buffer are. Everywhere else the same
    pick is `$(howto choose)`, which prints the invocation and inserts nothing.

    Examples:

    ```text
    eval "$(howto shell widgets zsh)"     in .zshrc, before the bindkey line
    howto shell widgets zsh               read the block before you load it
    ```
    """
    raise typer.Exit(emit(shell, 'widgets'))


@app.command('completion')
def completion_command(shell: ShellArgument) -> None:
    """Print the completion script for the verbs and the card and Lab ids.

    Write it to a directory on your `fpath` as `_howto` before `compinit` runs,
    or source it after: `eval "$(howto shell completion zsh)"`.
    """
    raise typer.Exit(emit(shell, 'completion'))
